const Font = (() => {
  const chars = Object.keys(FONT_GLYPHS);
  const index = {};
  const atlas = makeCanvas(chars.length * 6, 7);
  const g = atlas.getContext('2d');
  g.fillStyle = '#fff';
  chars.forEach((ch, i) => {
    index[ch] = i;
    FONT_GLYPHS[ch].split(' ').forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') g.fillRect(i * 6 + x, y, 1, 1);
    });
  });
  const colored = {};
  const atlasFor = (color) => colored[color] || (colored[color] = tinted(atlas, color));

  function width(text, scale = 1) {
    return text.length * 6 * scale - scale;
  }

  // align: 'left' | 'center' | 'right'. shadow: color or null.
  function draw(ctx, text, x, y, { color = '#fff', scale = 1, align = 'left', shadow = '#000' } = {}) {
    text = String(text).toUpperCase();
    let ox = Math.round(align === 'center' ? x - width(text, scale) / 2 : align === 'right' ? x - width(text, scale) : x);
    y = Math.round(y);
    const passes = shadow ? [[shadow, scale, scale], [color, 0, 0]] : [[color, 0, 0]];
    for (const [col, dx, dy] of passes) {
      const src = atlasFor(col);
      for (let i = 0; i < text.length; i++) {
        const gi = index[text[i]] ?? index['?'];
        ctx.drawImage(src, gi * 6, 0, 5, 7, ox + i * 6 * scale + dx, y + dy, 5 * scale, 7 * scale);
      }
    }
  }
  return { draw, width };
})();
